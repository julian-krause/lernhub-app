  handyInfo: (pruefen) => ipcRenderer.invoke('handy:info', !!pruefen),
  handyFreigeben: () => ipcRenderer.invoke('handy:freigeben'),
  handyAufheben: () => ipcRenderer.invoke('handy:aufheben'),
